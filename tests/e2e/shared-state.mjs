import assert from "node:assert/strict";
import { DateTime } from "luxon";

const url = process.env.SHARETOO_TEST_URL ?? "http://127.0.0.1:3101";
const password = process.env.DEMO_ADMIN_PASSWORD;
if (!password) throw Error("Set the demo password for the disposable integration workspace.");
const endpoint = url + "/api/state";
const send = (data,cookie) => fetch(endpoint,{method:"POST",headers:{"Content-Type":"application/json",...(cookie?{Cookie:cookie}:{})},body:JSON.stringify(data)});
const read = (cookie,query="") => fetch(endpoint+query,{headers:cookie?{Cookie:cookie}:{}});
const login = await send({type:"login",password});
assert.equal(login.status,200,await login.clone().text().then((value)=>value.slice(0,200)));
const cookie = login.headers.get("set-cookie")?.split(";")[0];
assert.ok(cookie);
const unauthorized = await send({type:"reset"});
assert.equal(unauthorized.status,401);
const today=DateTime.now().setZone("Europe/Ljubljana").startOf("day");
const local=(days,hour)=>today.plus({days}).set({hour}).toFormat("yyyy-MM-dd'T'HH:mm");
const names=["Shared Sample Alpha","Shared Sample Beta"];
const requests=names.map((name,i)=>({type:"request",id:crypto.randomUUID(),vehicleId:"golf",pickup:local(16,10),returnAt:local(17,10),name,email:"sharetoo-test-"+i+"@example.com",phone:"+386 01 234 56 78",note:"",accept:true,eligibility:true}));
const submissions=await Promise.all(requests.map(async (request)=>{
  const response=await send(request);
  assert.equal(response.status,200);
  return response.json();
}));
assert.ok(submissions.every((value)=>value.receipt.status==="REQUESTED"));
const state=await read(cookie).then((response)=>response.json());
assert.equal(state.state.bookings.filter((booking)=>requests.some((request)=>request.id===booking.id)).length,2);
const outcomes=await Promise.all(requests.map(async ({id})=>(await send({type:"status",id,status:"CONFIRMED"},cookie)).status));
assert.deepEqual(outcomes.sort(),[200,409]);
const owner=await read(cookie).then((response)=>response.json());
const confirmed=owner.state.bookings.find((booking)=>requests.some((request)=>request.id===booking.id)&&booking.status==="CONFIRMED");
assert.ok(confirmed.contract);
assert.equal(confirmed.activity.filter((event)=>event.type==="BOOKING_CONFIRMED_CUSTOMER").length,1);
const publicResponse=await read(undefined,"?ref="+confirmed.ref).then((response)=>response.json());
assert.equal(publicResponse.receipt.status,"CONFIRMED");
assert.equal(JSON.stringify(publicResponse).includes(confirmed.customer.email),false);
assert.equal(JSON.stringify(publicResponse).includes(confirmed.contract.plate),false);
assert.equal((await send({...requests[0],id:crypto.randomUUID()})).status,409);
await send({type:"status",id:confirmed.id,status:"CANCELLED"},cookie);
assert.equal((await send({...requests[0],id:crypto.randomUUID()})).status,200);
console.log("Shared state, owner access, public privacy, conflicting approvals and cancellation verified.");
